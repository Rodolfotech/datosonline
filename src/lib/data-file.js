// Pure logic to write and read the files in src/data/ (products.js and
// categories.js). They are JavaScript modules so the site can import them
// directly, but their content is strict JSON so the admin panel can read them
// back and rewrite them. No DOM access: tested with node --test.

const HEADER = `// Generated by the admin panel. Do not edit by hand: the panel rewrites the
// whole file and can only read it back while it keeps this format.
`;

const EXPORT_NAME = /^[A-Za-z_$][\w$]*$/;
const DATA_FILE = /^(?:\/\/[^\n]*\n)*export const [A-Za-z_$][\w$]* = (\[[\s\S]*\]);\n?$/;
const FORMAT_ERROR = "El archivo de datos no tiene el formato esperado.";

// Returns the text of a module that exports `value` (a list) as `exportName`.
export function serializeDataFile(exportName, value) {
  if (!EXPORT_NAME.test(exportName)) throw new Error(`Nombre de exportación no válido: ${exportName}`);
  return `${HEADER}export const ${exportName} = ${JSON.stringify(value, null, 2)};\n`;
}

// Returns the list stored in a file written by serializeDataFile.
export function parseDataFile(text) {
  const match = DATA_FILE.exec(text);
  if (!match) throw new Error(FORMAT_ERROR);
  try {
    return JSON.parse(match[1]);
  } catch {
    throw new Error(FORMAT_ERROR);
  }
}
